// Build the standalone browser bundle used by the WebGPU parity harness.
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
await build({
  entryPoints: [join(here, "../src/webgpu/paged-attention.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  outfile: join(here, "webgpu-paged-attention/paged-attention.bundle.js"),
  banner: { js: "// GENERATED by scripts/build-wgsl-harness.mjs; do not edit." },
});
console.log("wrote scripts/webgpu-paged-attention/paged-attention.bundle.js");
